// cqltestsgen generates parity fixtures from the HL7 CQL conformance suite
// (github.com/cqframework/cql-tests).
//
// Each suite file becomes one CQL library under
// test/corpus/cqframework/cql-tests/, with one define per test expression.
// The suite is Apache-2.0 and the generated libraries are committed, so the
// corpus does not need the suite checked out to run; regenerate after
// refreshing tools/cql-tests:
//
//	task corpus:cql-tests
//
// Two kinds of test are left out. Tests the suite itself marks
// invalid="syntax" or invalid="semantic" are expected translation failures and
// would fail their whole library. Tests the pinned CQF release rejects are
// listed in cqfRejects with the reason; they are upstream disagreements with
// the suite, not echo-elm gaps.
package main

import (
	"context"
	"encoding/xml"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const (
	suiteDir = "tools/cql-tests/tests/cql"
	outDir   = "test/corpus/cqframework/cql-tests"
)

// cqfRejects are tests that CQF 5.0.0 fails to translate, keyed by
// "<file>/<group>.<test>".
var cqfRejects = map[string]string{
	"CqlDateTimeOperatorsTest/Uncertainty tests.TimeDurationBetweenHourDiffPrecision":    "syntax error at 'Z' in a Time literal",
	"CqlDateTimeOperatorsTest/DateTimeComponentFrom.DateTimeComponentFromTimezoneOffset": "the timezone keyword is only valid at compatibility level 1.3 or lower",
	"CqlListOperatorsTest/Slice.SliceAll":                                                "no public Slice overload",
	"CqlListOperatorsTest/Slice.SliceEmpty":                                              "no public Slice overload",
	"CqlListOperatorsTest/Slice.SliceNull":                                               "no public Slice overload",
	"CqlListOperatorsTest/Slice.SliceStart":                                              "no public Slice overload",
	"CqlListOperatorsTest/Slice.SliceStartNull":                                          "no public Slice overload",
	"CqlListOperatorsTest/Slice.SliceEnd":                                                "no public Slice overload",
	"CqlListOperatorsTest/Slice.SliceEndNull":                                            "no public Slice overload",
	"CqlListOperatorsTest/Slice.SliceNegative":                                           "no public Slice overload",
	"CqlListOperatorsTest/Slice.SliceStartAndNegative":                                   "no public Slice overload",
	"CqlListOperatorsTest/Slice.SlicePast":                                               "no public Slice overload",
}

type suite struct {
	Groups []struct {
		Name  string `xml:"name,attr"`
		Tests []struct {
			Name       string `xml:"name,attr"`
			Expression struct {
				Invalid string `xml:"invalid,attr"`
				Text    string `xml:",chardata"`
			} `xml:"expression"`
		} `xml:"test"`
	} `xml:"group"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "cqltestsgen: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	files, err := filepath.Glob(filepath.Join(suiteDir, "*.xml"))
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("no suite files under %s — clone github.com/cqframework/cql-tests into tools/cql-tests", suiteDir)
	}
	sort.Strings(files)
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	var libs []string
	defines, skippedInvalid, skippedCQF := 0, 0, 0
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		var s suite
		if err := xml.Unmarshal(raw, &s); err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		lib := strings.TrimSuffix(filepath.Base(f), ".xml")
		var b strings.Builder
		fmt.Fprintf(&b, "// Generated by internal/tools/cqltestsgen from the HL7 CQL conformance\n")
		fmt.Fprintf(&b, "// suite (%s). Do not edit; see PROVENANCE.md.\n", filepath.Base(f))
		fmt.Fprintf(&b, "library %s version '1.0'\n\ncontext Unfiltered\n", lib)
		for _, g := range s.Groups {
			for _, t := range g.Tests {
				expr := strings.TrimSpace(t.Expression.Text)
				if expr == "" {
					continue
				}
				if inv := t.Expression.Invalid; inv == "syntax" || inv == "semantic" {
					skippedInvalid++
					continue
				}
				name := g.Name + "." + t.Name
				if _, rejected := cqfRejects[lib+"/"+name]; rejected {
					skippedCQF++
					continue
				}
				fmt.Fprintf(&b, "\ndefine %q:\n", name)
				for line := range strings.SplitSeq(expr, "\n") {
					fmt.Fprintf(&b, "  %s\n", strings.TrimRight(line, " \t\r"))
				}
				defines++
			}
		}
		if err := os.WriteFile(filepath.Join(outDir, lib+".cql"), []byte(b.String()), 0o644); err != nil {
			return err
		}
		libs = append(libs, lib)
	}

	commit := "unknown"
	if out, err := exec.CommandContext(context.Background(), "git", "-C", "tools/cql-tests", "log", "-1", "--format=%H %cs").Output(); err == nil {
		commit = strings.TrimSpace(string(out))
	}
	if err := writeProvenance(libs, defines, skippedInvalid, skippedCQF, commit); err != nil {
		return err
	}
	fmt.Printf("wrote %d libraries, %d defines to %s (skipped %d invalid, %d CQF-rejected)\n",
		len(libs), defines, outDir, skippedInvalid, skippedCQF)
	return nil
}

func writeProvenance(libs []string, defines, invalid, rejected int, commit string) error {
	var b strings.Builder
	b.WriteString("# cql-tests provenance\n\n")
	b.WriteString("Generated from the HL7 CQL conformance suite by `internal/tools/cqltestsgen`.\n\n")
	b.WriteString("| Field | Value |\n|---|---|\n")
	b.WriteString("| **Repository** | https://github.com/cqframework/cql-tests |\n")
	fmt.Fprintf(&b, "| **Commit** | `%s` |\n", commit)
	b.WriteString("| **License** | Apache-2.0 (see NOTICE) |\n")
	b.WriteString("| **Modifications** | Each suite file's test expressions are wrapped as `define`s in one library; expressions are unchanged |\n\n")
	fmt.Fprintf(&b, "%d libraries, %d defines.\n\n", len(libs), defines)
	fmt.Fprintf(&b, "Left out: %d tests the suite marks `invalid=\"syntax\"` or `invalid=\"semantic\"` (expected translation failures), ", invalid)
	fmt.Fprintf(&b, "and %d the pinned CQF release rejects:\n\n", rejected)
	keys := make([]string, 0, len(cqfRejects))
	for k := range cqfRejects {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b.WriteString("| Test | CQF 5.0.0 |\n|---|---|\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "| `%s` | %s |\n", k, cqfRejects[k])
	}
	return os.WriteFile(filepath.Join(outDir, "PROVENANCE.md"), []byte(b.String()), 0o644)
}
